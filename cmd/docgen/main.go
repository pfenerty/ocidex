// Command docgen writes the docs site's generated reference pages (ADR-0057):
// the configuration reference from internal/config, the authorization matrix
// from the router's authRules, and the Helm values reference from each chart's
// values.yaml. The CLI reference comes from `ocidex-cli gen-reference`, which
// owns its own command tree.
//
// Usage:
//
//	go run ./cmd/docgen -out site/src/content/docs/reference
//
// `make docs-generate` runs it; `make docs-generate-check` regenerates into a
// temporary directory and fails when a committed page differs.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
)

// githubBlob is where repo-relative links in generated pages point, since the
// site does not carry the repository's files.
const githubBlob = "https://github.com/pfenerty/ocidex/blob/main/"

// generatedNote heads every page. Starlight renders the frontmatter title, so
// pages carry no H1 of their own.
const generatedNote = "<!-- Generated by `make docs-generate` (cmd/docgen). Do not edit by hand. -->\n"

func main() {
	out := flag.String("out", "", "directory to write the reference pages into")
	charts := flag.String("charts", "charts", "directory holding the Helm charts")
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "docgen: -out is required")
		os.Exit(2)
	}
	if err := run(*out, *charts); err != nil {
		fmt.Fprintf(os.Stderr, "docgen: %v\n", err)
		os.Exit(1)
	}
}

func run(out, charts string) error {
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	helm, err := helmValuesPage(charts)
	if err != nil {
		return err
	}
	pages := map[string]string{
		"configuration.md": configurationPage(),
		"authorization.md": authorizationPage(),
		"helm-values.md":   helm,
	}
	for name, body := range pages {
		if err := os.WriteFile(filepath.Join(out, name), []byte(body), 0o644); err != nil { //nolint:gosec // docs are world-readable
			return err
		}
	}
	return nil
}

// frontmatter renders a Starlight page header.
func frontmatter(title, description string, order int) string {
	return fmt.Sprintf("---\ntitle: %q\ndescription: %q\nsidebar:\n  order: %d\n---\n\n%s\n", title, description, order, generatedNote)
}
