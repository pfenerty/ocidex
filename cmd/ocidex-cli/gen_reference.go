package main

import (
	"fmt"
	"io"
	"os"
	"regexp"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// newGenReferenceCmd writes the docs site's CLI reference page (ADR-0057) from
// the command tree itself, so the page cannot drift from the binary. It is
// hidden: it is a build tool, not something a user runs. `make docs-generate`
// calls it, and `make docs-generate-check` fails when the committed page is stale.
func newGenReferenceCmd(root *cobra.Command) *cobra.Command {
	return &cobra.Command{
		Use:    "gen-reference",
		Short:  "Write the CLI reference page for the docs site",
		Hidden: true,
		Args:   cobra.NoArgs,
		// Overrides the root's: the page needs no server, key or config file.
		PersistentPreRunE: func(*cobra.Command, []string) error { return nil },
		RunE: func(c *cobra.Command, _ []string) error {
			return writeReference(c.OutOrStdout(), root)
		},
	}
}

func writeReference(w io.Writer, root *cobra.Command) error {
	var b strings.Builder
	b.WriteString(`---
title: CLI
description: Every ocidex-cli command and flag.
sidebar:
  order: 4
---

<!-- Generated by ` + "`make docs-generate`" + ` (ocidex-cli gen-reference). Do not edit by hand. -->

`)
	b.WriteString(prose(root.Long) + "\n")
	fmt.Fprintf(&b, "\n## Global flags\n\nEvery command accepts these.\n\n%s", flagTable(root.PersistentFlags()))
	for _, c := range root.Commands() {
		writeCommand(&b, c)
	}
	out := blankRuns.ReplaceAllString(b.String(), "\n\n")
	// Help text that names the config file resolves it against the generating
	// user's home; the page must say ~ so it is the same on every machine.
	if home, err := os.UserHomeDir(); err == nil && home != "" {
		out = strings.ReplaceAll(out, home+string(os.PathSeparator), "~/")
	}
	_, err := io.WriteString(w, strings.TrimRight(out, "\n")+"\n")
	return err
}

// blankRuns collapses the blank lines that sections without a body leave.
var blankRuns = regexp.MustCompile(`\n{3,}`)

// bareURL matches a URL in help text that is not already in backticks.
var bareURL = regexp.MustCompile("(^|[\\s(])(https?://[^\\s)`]+)")

// prose escapes help text for Markdown: "<id>" would otherwise be read as an
// HTML tag and vanish from the page, and a bare URL (often a localhost default)
// would become a link.
func prose(s string) string {
	s = strings.NewReplacer("<", "&lt;", ">", "&gt;").Replace(strings.TrimSpace(s))
	return bareURL.ReplaceAllString(s, "$1`$2`")
}

// writeCommand documents one command and, depth first, its subcommands. A
// command that only groups others gets a heading and its description.
func writeCommand(b *strings.Builder, c *cobra.Command) {
	if c.Hidden || c.Name() == "help" || c.Name() == "completion" {
		return
	}
	level := strings.Repeat("#", min(2+strings.Count(c.CommandPath(), " ")-1, 4))
	fmt.Fprintf(b, "\n%s %s\n\n", level, c.CommandPath())
	desc := c.Long
	if desc == "" {
		desc = c.Short
	}
	if desc != "" {
		b.WriteString(prose(desc) + "\n\n")
	}
	if c.Runnable() {
		fmt.Fprintf(b, "```\n%s\n```\n\n", c.UseLine())
		if c.Example != "" {
			fmt.Fprintf(b, "Examples:\n\n```sh\n%s\n```\n\n", strings.TrimRight(c.Example, "\n"))
		}
		if t := flagTable(c.LocalNonPersistentFlags()); t != "" {
			b.WriteString(t)
		}
	}
	for _, sub := range c.Commands() {
		writeCommand(b, sub)
	}
}

func flagTable(fs *pflag.FlagSet) string {
	var rows []string
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Name == "help" {
			return
		}
		name := "`--" + f.Name + "`"
		if f.Shorthand != "" {
			name = "`-" + f.Shorthand + "`, " + name
		}
		def := ""
		if f.DefValue != "" && f.DefValue != "false" && f.DefValue != "[]" {
			def = "`" + f.DefValue + "`"
		}
		usage := strings.ReplaceAll(prose(f.Usage), "|", `\|`)
		rows = append(rows, fmt.Sprintf("| %s | %s | %s |", name, def, usage))
	})
	if len(rows) == 0 {
		return ""
	}
	return "| Flag | Default | Description |\n| --- | --- | --- |\n" + strings.Join(rows, "\n") + "\n\n"
}
